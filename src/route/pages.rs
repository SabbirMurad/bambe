use actix_web::web;
use crate::Markup;

pub fn router(cfg: &mut web::ServiceConfig) {
    cfg.service(
        web::scope("")
        /* ── Storefront ─────────────────────────────────── */
        .route(
            "/",
            web::get().to(Markup::home)
        )
        .route(
            "/listing",
            web::get().to(Markup::listing)
        )
        .route(
            "/product",
            web::get().to(Markup::product_legacy)
        )
        .route(
            "/product/{slug}",
            web::get().to(Markup::product)
        )
        .route(
            "/favicon.ico",
            web::get().to(crate::seo::favicon)
        )
        .route(
            "/robots.txt",
            web::get().to(crate::seo::robots)
        )
        .route(
            "/sitemap.xml",
            web::get().to(crate::seo::sitemap)
        )
        .route(
            "/feeds/google.xml",
            web::get().to(crate::seo::merchant_feed)
        )
        .route(
            "/search",
            web::get().to(Markup::search)
        )
        .route(
            "/wishlist",
            web::get().to(Markup::wishlist)
        )
        .route(
            "/about",
            web::get().to(Markup::about)
        )
        .route(
            "/privacy",
            web::get().to(Markup::privacy)
        )
        .route(
            "/terms",
            web::get().to(Markup::terms)
        )

        /* ── Checkout ───────────────────────────────────── */
        .route(
            "/cart",
            web::get().to(Markup::cart)
        )
        .route(
            "/checkout/address",
            web::get().to(Markup::checkout_address)
        )
        .route(
            "/checkout/payment",
            web::get().to(Markup::checkout_payment)
        )
        .route(
            "/checkout/review",
            web::get().to(Markup::checkout_review)
        )
        .route(
            "/checkout/confirmation",
            web::get().to(Markup::checkout_confirmation)
        )

        /* ── Account ────────────────────────────────────── */
        .route(
            "/account/profile",
            web::get().to(Markup::account_profile)
        )
        .route(
            "/account/orders",
            web::get().to(Markup::account_orders)
        )
        .route(
            "/account/tracking",
            web::get().to(Markup::account_tracking)
        )
        .route(
            "/account/notifications",
            web::get().to(Markup::account_notifications)
        )
        .route(
            "/account/rewards",
            web::get().to(Markup::account_rewards)
        )
        .route(
            "/account/returns",
            web::get().to(Markup::account_returns)
        )
        .route(
            "/account/support",
            web::get().to(Markup::account_support)
        )

        /* ── Auth ───────────────────────────────────────── */
        .route(
            "/login",
            web::get().to(Markup::sign_in)
        )
        .route(
            "/register",
            web::get().to(Markup::sign_up)
        )
        .route(
            "/forgot-password",
            web::get().to(Markup::forgot_password)
        )

        /*
          ── Admin console ──────────────────────────────────
          These only collide with the JSON API by prefix, not by
          path: the admin endpoints live under /api/v1/admin.
        */
        .route(
            "/admin/login",
            web::get().to(Markup::admin_sign_in)
        )
        .route(
            "/admin",
            web::get().to(Markup::admin_overview)
        )
        .route(
            "/admin/products",
            web::get().to(Markup::admin_products)
        )
        .route(
            "/admin/products/new",
            web::get().to(Markup::admin_product_new)
        )
        .route(
            "/admin/categories",
            web::get().to(Markup::admin_categories)
        )
        .route(
            "/admin/orders",
            web::get().to(Markup::admin_orders)
        )
        .route(
            "/admin/returns",
            web::get().to(Markup::admin_returns)
        )
        .route(
            "/admin/reviews",
            web::get().to(Markup::admin_reviews)
        )
        .route(
            "/admin/customers",
            web::get().to(Markup::admin_customers)
        )
        .route(
            "/admin/coupons",
            web::get().to(Markup::admin_coupons)
        )
        .route(
            "/admin/support",
            web::get().to(Markup::admin_support)
        )
        .route(
            "/admin/settings",
            web::get().to(Markup::admin_settings)
        )
    );
}
